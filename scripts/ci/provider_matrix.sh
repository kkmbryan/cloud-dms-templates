#!/usr/bin/env bash
# ==============================================================================
# Validate one Terraform root against a given google provider version, without
# touching the committed .terraform.lock.hcl.
#
# The repository is copied to a temporary directory (so ../../modules paths
# still resolve). In the copy, the root gets a ci_provider_override.tf that
# pins the google provider, and `terraform init -upgrade` re-resolves it.
#
# Usage: scripts/ci/provider_matrix.sh <root-dir> <version|latest>
#   scripts/ci/provider_matrix.sh templates/01-live-migration-gce-cdc 8.0.0
#   scripts/ci/provider_matrix.sh templates/01-live-migration-gce-cdc latest
# "latest" keeps the root's own constraint (>= 8.0, < 9.0) and resolves the
# newest matching release.
# Env: RUN_TESTS=1 also runs `terraform test` (mocked, plan-only) when the root
#      has a tests/ directory.
#      KEEP_WORKDIR=1 keeps the temporary copy for debugging.
# ==============================================================================
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <root-dir> <version|latest>" >&2
  exit 2
fi

root="${1%/}"
version="$2"
repo="$(git rev-parse --show-toplevel)"

if [[ ! -d "${repo}/${root}" ]]; then
  echo "ERROR: ${root} is not a directory in ${repo}" >&2
  exit 2
fi
if [[ "${version}" != "latest" && ! "${version}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "ERROR: version must be X.Y.Z or latest, got '${version}'" >&2
  exit 2
fi

work="$(mktemp -d "${TMPDIR:-/tmp}/tf-provider-matrix.XXXXXX")"
cleanup() {
  if [[ "${KEEP_WORKDIR:-0}" != "1" ]]; then
    rm -rf "${work}"
  else
    echo "Kept ${work}"
  fi
}
trap cleanup EXIT

# Copy tracked and untracked (not ignored) files only: no .terraform, no state.
git -C "${repo}" ls-files -z --cached --others --exclude-standard |
  (cd "${repo}" && xargs -0 cp --parents -t "${work}")
# Lock files are git-ignored except for roots; copy the root's lock if present.
if [[ -f "${repo}/${root}/.terraform.lock.hcl" ]]; then
  cp "${repo}/${root}/.terraform.lock.hcl" "${work}/${root}/"
fi

cd "${work}/${root}"

if [[ "${version}" != "latest" ]]; then
  cat >ci_provider_override.tf <<EOF
# Generated by scripts/ci/provider_matrix.sh (temporary copy only).
terraform {
  required_providers {
    google = {
      source  = "hashicorp/google"
      version = "= ${version}"
    }
  }
}
EOF
fi

echo "== ${root}: google provider ${version}"
terraform init -backend=false -input=false -upgrade -no-color >/dev/null
terraform providers -no-color | sed -n '1,20p'
grep -A1 'registry.terraform.io/hashicorp/google"' .terraform.lock.hcl | sed -n '2p'
terraform validate -no-color

if [[ "${RUN_TESTS:-0}" == "1" && -d tests ]]; then
  terraform test -no-color
fi
